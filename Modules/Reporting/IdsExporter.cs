using System.Text;
using SecKit.Core;
using SecKit.Models;

namespace SecKit.Modules.Reporting;

/// <summary>
/// Generates Snort and Suricata IDS/IPS rules from attack patterns discovered during scanning.
/// </summary>
public class IdsExporter
{
    private readonly string _outputDir;
    private int _snortSid = 1000001;

    public IdsExporter(string outputDir)
    {
        _outputDir = Path.Combine(outputDir, "reports");
        Directory.CreateDirectory(_outputDir);
    }

    /// <summary>
    /// Generates Snort and Suricata rule files from vulnerability findings.
    /// </summary>
    public async Task<IdsReport> GenerateAsync(IEnumerable<Vulnerability> vulnerabilities)
    {
        var vulns = vulnerabilities.ToList();
        var report = new IdsReport();

        if (vulns.Count == 0)
        {
            Logger.Info("No vulnerabilities provided; skipping IDS rule generation.");
            return report;
        }

        // Generate Snort rules
        var snortPath = Path.Combine(_outputDir, "snort.rules");
        var snortRules = GenerateSnortRules(vulns);
        await File.WriteAllTextAsync(snortPath, snortRules);
        report.SnortPath = snortPath;
        report.SnortRuleCount = snortRules.Split('\n').Count(l => l.StartsWith("alert "));

        // Generate Suricata rules (same format, different output file)
        var suricataPath = Path.Combine(_outputDir, "suricata.rules");
        var suricataRules = GenerateSuricataRules(vulns);
        await File.WriteAllTextAsync(suricataPath, suricataRules);
        report.SuricataPath = suricataPath;
        report.SuricataRuleCount = suricataRules.Split('\n').Count(l => l.StartsWith("alert "));

        Logger.Info($"IDS rules generated: Snort={report.SnortRuleCount}, Suricata={report.SuricataRuleCount}");
        return report;
    }

    #region Snort Rules

    private string GenerateSnortRules(List<Vulnerability> vulns)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# ================================================================");
        sb.AppendLine("# Snort IDS Rules — Generated by SecKit");
        sb.AppendLine($"# Generated: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine($"# Rules generated from {vulns.Count} vulnerability findings");
        sb.AppendLine("# ================================================================");
        sb.AppendLine();

        foreach (var v in vulns.OrderBy(v => v.Severity))
        {
            switch (v.Type.ToLowerInvariant())
            {
                case "sql injection":
                case "sqli":
                    GenerateSnortSqli(sb, v);
                    break;
                case "xss":
                case "cross-site scripting":
                    GenerateSnortXss(sb, v);
                    break;
                case "path traversal":
                case "directory traversal":
                    GenerateSnortPathTraversal(sb, v);
                    break;
                case "command injection":
                case "os command injection":
                    GenerateSnortCommandInjection(sb, v);
                    break;
                case "ssrf":
                case "server-side request forgery":
                    GenerateSnortSsrf(sb, v);
                    break;
            }
        }

        return sb.ToString();
    }

    private void GenerateSnortSqli(StringBuilder sb, Vulnerability v)
    {
        var msg = $"SQL Injection Attempt — {v.Severity} finding on {v.Url}";
        var classification = v.Severity switch { "Critical" => "Attempted Administrator Privilege Gain", "High" => "Web Application Attack", _ => "Web Application Attack" };
        var priority = v.Severity switch { "Critical" => 1, "High" => 2, _ => 3 };

        sb.AppendLine($"# Rule: SQLi — {v.Url} (Confidence: {v.Confidence}%)");
        sb.AppendLine($"alert tcp $EXTERNAL_NET any -> $HOME_NET $HTTP_PORTS (");
        sb.AppendLine($"  msg:\"{msg}\";");
        sb.AppendLine($"  flow:to_server,established;");
        sb.AppendLine($"  content:\"union\"; nocase; http_uri;");
        sb.AppendLine($"  content:\"select\"; nocase; http_uri; distance:0;");
        sb.AppendLine($"  metadata:service http, seckit-sqli;");
        sb.AppendLine($"  reference:url,{v.Url};");
        sb.AppendLine($"  classtype:{classification};");
        sb.AppendLine($"  sid:{_snortSid}; rev:1; priority:{priority};");
        sb.AppendLine($")");
        sb.AppendLine();
        _snortSid++;

        sb.AppendLine($"# Rule: SQLi — OR 1=1 pattern");
        sb.AppendLine($"alert tcp $EXTERNAL_NET any -> $HOME_NET $HTTP_PORTS (");
        sb.AppendLine($"  msg:\"SQL Injection — Boolean-based OR 1=1\";");
        sb.AppendLine($"  flow:to_server,established;");
        sb.AppendLine($"  pcre:\"/[?&][^=]+=(%27|')(%20|\\s)*[Oo][Rr](%20|\\s)*[0-9](%20|\\s)*=(%20|\\s)*[0-9]/i\";");
        sb.AppendLine($"  metadata:service http, seckit-sqli;");
        sb.AppendLine($"  reference:url,{v.Url};");
        sb.AppendLine($"  classtype:Web Application Attack;");
        sb.AppendLine($"  sid:{_snortSid}; rev:1; priority:2;");
        sb.AppendLine($")");
        sb.AppendLine();
        _snortSid++;
    }

    private void GenerateSnortXss(StringBuilder sb, Vulnerability v)
