        sb.AppendLine($"  http.uri; content:\"union\"; nocase;");
        sb.AppendLine($"  http.uri; content:\"select\"; nocase; distance:0;");
        sb.AppendLine($"  metadata:service http, seckit-sqli;");
        sb.AppendLine($"  reference:url,{v.Url};");
        sb.AppendLine($"  classtype:Web Application Attack;");
        sb.AppendLine($"  sid:{_snortSid}; rev:1;");
        sb.AppendLine($")");
