        sb.AppendLine($"  msg:\"XSS — Event Handler Injection (onerror/onload)\";");
        sb.AppendLine($"  flow:to_server,established;");
        sb.AppendLine($"  pcre:\"/(onerror|onload|onclick|onmouseover)\\s*=/i\";");
        sb.AppendLine($"  metadata:service http, seckit-xss;");
        sb.AppendLine($"  reference:url,{v.Url};");
        sb.AppendLine($"  classtype:Web Application Attack;");
        sb.AppendLine($"  sid:{_snortSid}; rev:1; priority:2;");
        sb.AppendLine($")");
