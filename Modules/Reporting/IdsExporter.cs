    #endregion

    #region Suricata Rules

    private string GenerateSuricataRules(List<Vulnerability> vulns)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# ================================================================");
        sb.AppendLine("# Suricata IDS/IPS Rules — Generated by SecKit");
        sb.AppendLine($"# Generated: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine($"# Rules generated from {vulns.Count} vulnerability findings");
        sb.AppendLine("# ================================================================");
        sb.AppendLine();

        // Suricata uses the same base format as Snort but adds app-layer support
        foreach (var v in vulns.OrderBy(v => v.Severity))
        {
            var type = v.Type.ToLowerInvariant();
            if (type is "sql injection" or "sqli")
                GenerateSuricataSqli(sb, v);
            else if (type is "xss" or "cross-site scripting")
                GenerateSuricataXss(sb, v);
            else if (type is "path traversal" or "directory traversal")
                GenerateSuricataPathTraversal(sb, v);
            else if (type is "command injection" or "os command injection")
                GenerateSuricataCommandInjection(sb, v);
            else if (type is "ssrf" or "server-side request forgery")
                GenerateSuricataSsrf(sb, v);
        }

        return sb.ToString();
    }

