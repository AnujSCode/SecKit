/// <summary>Report of generated IDS rules.</summary>
public class IdsReport
{
    public string SnortPath { get; set; } = string.Empty;
    public int SnortRuleCount { get; set; }
    public string SuricataPath { get; set; } = string.Empty;
    public int SuricataRuleCount { get; set; }

    public int TotalRules => SnortRuleCount + SuricataRuleCount;
}
